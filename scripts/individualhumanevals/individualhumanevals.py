            ax.set_xlabel('Rating (1-5)', fontsize=10, fontweight='bold')
            ax.set_ylabel('Number of Evals', fontsize=10, fontweight='bold')

            # Set x-axis ticks and labels
            ax.set_xticks(x_positions)
            ax.set_xticklabels(['1', '2', '3', '4', '5'], fontsize=10)

