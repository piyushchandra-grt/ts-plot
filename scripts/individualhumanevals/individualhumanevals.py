def save_individual_subplots(all_data, output_dir="individual_graphs"):
    """
    Save each subplot from the cross-language analysis as individual image files

    Parameters:
    all_data: dict - Data organized by category from load_all_languages_data()
    output_dir: str - Directory to save individual graph images

    Returns:
    dict - Summary of saved files organized by category
    """
    import os
    import matplotlib.pyplot as plt
    import numpy as np
    from collections import Counter

    # Create output directory if it doesn't exist
    if not os.path.exists(output_dir):
        os.makedirs(output_dir)
        print(f"📁 Created directory: {output_dir}")

    # Language and domain configuration - Corrected language names to match dictionary keys
    languages = ["Python", "JavaScript", "Java", "C++"] # Updated language names
    language_domains = {
        "Python": ["Overall", "Machine Learning", "FinTech", "EdTech"],
        "JavaScript": ["Overall", "Social Networking", "Media", "Streaming"],
        "Java": ["Overall", "E‑Commerce", "CRM", "Hotel"],
        "C++": ["Overall", "Gaming", "IoT", "Security"]
    }

    # Model configuration
    models = ['Chat GPT o4-mini-high', 'Gemini 2.5 pro', 'Claude Opus 4']
    model_colors = {
        'Chat GPT o4-mini-high': '#F93E3E',
        'Gemini 2.5 pro': '#5CD167',
        'Claude Opus 4': '#1F77B4'
    }
    model_display_names = {
        'Chat GPT o4-mini-high': 'o4-mini-high',
        'Gemini 2.5 pro': 'Gemini 2.5 pro',
        'Claude Opus 4': 'Claude Opus 4'
    }

    rating_categories = ['Completeness', 'Correctness', 'Relevance']
    ratings = [1, 2, 3, 4, 5]
    bar_width = 0.25
    x_positions = np.arange(len(ratings))

    saved_files_summary = {}
    total_count = 0

    # Process each category
    for category in rating_categories:
        print(f"\n📊 Processing {category} category...")
        saved_files_summary[category] = []
        category_count = 0

        if category not in all_data:
            print(f"⚠️ Category '{category}' not found in data")
            continue

        category_data = all_data[category]

        # Process each language
        for language in languages:
            if language not in category_data:
                print(f"⚠️ No data for {language} in {category}")
                continue

            lang_data = category_data[language]

            # Process each domain for this language
            for domain in language_domains[language]:
                if domain not in lang_data:
                    continue

                domain_data = lang_data[domain]

                # Calculate rating distribution for each model
                model_counts = {}
                max_count = 0
                total_tasks = 0

                for model in models:
                    ratings_list = domain_data.get(model, [])
                    if ratings_list:
                        rating_counter = Counter(ratings_list)
                        counts_list = [rating_counter.get(r, 0) for r in ratings]
                        model_counts[model] = counts_list
                        max_count = max(max_count, max(counts_list))
                        total_tasks += sum(counts_list)
                    else:
                        model_counts[model] = [0, 0, 0, 0, 0]

                # Skip if no data
                if total_tasks == 0:
                    continue

                # Create individual figure
                fig, ax = plt.subplots(figsize=(8, 6))

                # Plot bars for each model
                for j, model in enumerate(models):
                    x_offset = x_positions + (j - 1) * bar_width
                    counts = model_counts[model]
                    n_tasks = sum(counts)

                    bars = ax.bar(x_offset, counts,
                                width=bar_width,
                                label=f'{model_display_names[model]}',
                                color=model_colors[model],
                                alpha=0.8,
                                edgecolor='white',
                                linewidth=1)

                # Customize the subplot
                ax.set_title(f'{category} Ratings: {language} - {domain}',
                           fontsize=14, fontweight='bold', pad=20)
                ax.set_xlabel('Rating (1-5)', fontsize=12, fontweight='bold')
                ax.set_ylabel('Number of Evals', fontsize=12, fontweight='bold')

                # Set x-axis
                ax.set_xticks(x_positions)
                ax.set_xticklabels(['1', '2', '3', '4', '5'], fontsize=11)

                # Set y-axis with appropriate limits
                y_limit = max_count + 3
                ax.set_ylim(0, y_limit)
                if y_limit <= 10:
                    tick_step = 1
                elif y_limit <= 20:
                    tick_step = 2
                else:
                    tick_step = 5
                ax.set_yticks(range(0, int(y_limit) + 1, tick_step))

                # Add grid
                ax.grid(True, axis='y', linestyle='--', alpha=0.4, color='gray')
                ax.set_axisbelow(True)

                # Add legend
                ax.legend(loc='upper left', fontsize=10, frameon=True,
                         fancybox=True, shadow=True)

                # Add summary text
                ax.text(0.02, 0.98, f'Total Tasks: {total_tasks}',
                       transform=ax.transAxes, fontsize=9,
                       verticalalignment='top',
                       bbox=dict(boxstyle='round,pad=0.3', facecolor='lightgray', alpha=0.7))

                plt.tight_layout()

                # Save the figure
                filename = f"{category.lower().replace(' ', '_')}_{language.lower().replace('+', 'plus')}_{domain.lower().replace(' ', '_').replace('-', '_').replace('‑', '_')}.png" # Added replace for + and special hyphen
                filepath = os.path.join(output_dir, filename)
                fig.savefig(filepath, dpi=300, bbox_inches='tight')
                plt.close(fig)

                saved_files_summary[category].append(filepath)
                category_count += 1
                total_count += 1

                print(f"  ✅ Saved: {filename} ({total_tasks} tasks)")

        print(f"📊 {category}: {category_count} individual graphs saved")

    # Print summary
    print(f"\n" + "="*60)
    print(f"📁 INDIVIDUAL SUBPLOT GENERATION COMPLETE")
    print(f"="*60)
    print(f"📊 Total individual graphs created: {total_count}")
    print(f"📁 All files saved in: {output_dir}/")

    for category in saved_files_summary:
        print(f"  {category}: {len(saved_files_summary[category])} graphs")

    return saved_files_summary

